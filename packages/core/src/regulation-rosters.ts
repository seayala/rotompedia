const M_A_LEGAL_SET = new Set<string>(
  M_A_LEGAL_SPECIES_RAW.map((name) => normalizeSpeciesKey(name))
);

const REGULATION_LEGAL_SETS: Partial<Record<RegulationCode, Set<string>>> = {
  "M-A": M_A_LEGAL_SET,
};

export function isSpeciesLegalInRegulation(
  regulationCode: RegulationCode | string,
  speciesName: string
): boolean {
  const allowed = REGULATION_LEGAL_SETS[regulationCode as RegulationCode];
  if (!allowed) return true;
  return allowed.has(normalizeSpeciesKey(speciesName));
}

export function getLegalSpeciesSetForRegulation(
  regulationCode: RegulationCode | string
): Set<string> | null {
  return REGULATION_LEGAL_SETS[regulationCode as RegulationCode] ?? null;
}
